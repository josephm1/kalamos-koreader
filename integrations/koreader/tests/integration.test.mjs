test('Android background handoff releases ink and invalidates queued paints without draining vectors', () => {
  const bridge = read('integrations/koreader/android-bridge/src/main/java/com/kalamos/koreader/KalamosBridge.kt')
  assert.match(bridge, /onActivityPaused\(activity: Activity\) = suspendHost\(activity\)/)
  assert.match(bridge, /onActivityStopped\(activity: Activity\) = suspendHost\(activity\)/)
  const suspend = bridge.slice(bridge.indexOf('private fun suspendHost'), bridge.indexOf('private val completed'))
  assert.match(suspend, /hostForeground = false/)
  assert.match(suspend, /lifecycleGeneration \+= 1/)
  assert.match(suspend, /stopInkOnUiThread\(\)/)
  assert.doesNotMatch(suspend, /completed\.(clear|poll)/)
  assert.match(bridge, /requestLifecycleGeneration != lifecycleGeneration/)
  assert.match(bridge, /\.put\("suspended", inkSuspended\)/)
  const main = read('integrations/koreader/kalamos.koplugin/main.lua')
  const checkpoint = main.slice(main.indexOf('function Kalamos:checkpointInkPage'), main.indexOf('function Kalamos:saveInkPage'))
  assert.ok(checkpoint.indexOf('applyInkBatch') < checkpoint.indexOf('if batch.suspended'))
  assert.match(checkpoint, /self.ink_watch_generation = self.ink_watch_generation \+ 1/)
  assert.match(checkpoint, /self.ink_mode = nil/)
})


